# =========================================
# 2. Generate date range (weekdays only)
# =========================================
start_date = datetime(2026, 6, 1)
end_date = datetime(2026, 8, 18)
date_range = pd.date_range(start=start_date, end=end_date, freq='B')  # 'B' = business days

# =========================================
# 3. Generate realistic stock data
# =========================================
records = []

for symbol, name in stocks.items():
    # Starting price: random between 10 and 500
    price = np.random.uniform(10, 500)
    
    for trade_date in date_range:
        # Random daily volatility (0.5% to 3%)
        daily_return = np.random.normal(0, 0.015)  # mean 0, std 1.5%
        
        # Calculate OHLC
        open_price = price * (1 + np.random.uniform(-0.005, 0.005))
        close_price = open_price * (1 + daily_return)
        high_price = max(open_price, close_price) * (1 + abs(np.random.normal(0, 0.005)))
        low_price = min(open_price, close_price) * (1 - abs(np.random.normal(0, 0.005)))
        
        # Ensure high > low and non-negative
        high_price = max(high_price, open_price, close_price) + 0.01
        low_price = min(low_price, open_price, close_price) - 0.01
        low_price = max(low_price, 0.1)  # prevent negative prices
        
        # Volume: random between 500 and 200,000
        volume = np.random.randint(500, 200000)
        
        # Turnover = close * volume (standard convention)
        turnover = close_price * volume
        
        # Percentage change (compared to previous close)
        # Since we track 'price' as yesterday's close, compute it
        pct_change = ((close_price - price) / price) * 100
        
        # Append record
        records.append({
            'trade_date': trade_date.strftime('%Y-%m-%d'),
            'symbol': symbol,
            'name': name,
            'open_price': round(open_price, 2),
            'high': round(high_price, 2),
            'low': round(low_price, 2),
            'close_price': round(close_price, 2),
            'volume': volume,
            'turnover': round(turnover, 2),
            'pct_change': round(pct_change, 4)
        })
        
        # Update base price for next day's percentage change
        price = close_price

# =========================================
# 4. Convert to DataFrame & Export
# =========================================
df = pd.DataFrame(records)

# Reorder columns to match your original structure
column_order = ['trade_date', 'symbol', 'name', 'open_price', 'high', 'low', 'close_price', 'volume', 'turnover', 'pct_change']
df = df[column_order]

# Sort by date, then symbol (optional)
df = df.sort_values(['trade_date', 'symbol']).reset_index(drop=True)

# Save to CSV
df.to_csv('dummy_stock_data.csv', index=False)

